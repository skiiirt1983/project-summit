#!/usr/bin/env python3
"""Builds firmware/services/audio/src/sounds_data.cpp from the source sounds in firmware/services/audio/assets/.

Each sound is converted with ffmpeg to 16 kHz mono, loudness-matched, trimmed (start/end in seconds below) with a short
fade-out, then stored as 8-bit mu-law (half the size of 16-bit, plenty for effects). Run it after changing a source
file or a trim, and commit the result:  python3 tools/make_sounds.py
"""
import array
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "firmware/services/audio/assets"
OUT = ROOT / "firmware/services/audio/src/sounds_data.cpp"
RATE = 16000

# name, file, start s, end s (None = whole file)
SOUNDS = [
    ("warning", "summit_warning_hit.wav", 0.0, None),
    ("usb", "summit_usb_plugin.wav", 0.0, None),
    ("alarm", "summit_cowbell.mp3", 0.30, 9.60),
]


def pcm(path, start, end):
    cmd = ["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ac", "1", "-ar", str(RATE)]
    filt = ["loudnorm=I=-16:TP=-1.5"]
    cmd += ["-af", ",".join(filt), "-f", "s16le", "-"]
    raw = subprocess.run(cmd, check=True, capture_output=True).stdout
    a = array.array("h")
    a.frombytes(raw)
    s = int(start * RATE)
    e = int(end * RATE) if end else len(a)
    a = a[s:e]
    fade = int(0.08 * RATE)  # 80 ms fade-out so a trimmed tail does not click
    for i in range(min(fade, len(a))):
        a[len(a) - 1 - i] = int(a[len(a) - 1 - i] * i / fade)
    return a


def ulaw(s):
    bias, clip = 0x84, 32635
    sign = 0x80 if s < 0 else 0
    s = min(abs(s), clip) + bias
    exp, mask = 7, 0x4000
    while exp > 0 and not (s & mask):
        exp -= 1
        mask >>= 1
    man = (s >> (exp + 3)) & 0x0F
    return (~(sign | (exp << 4) | man)) & 0xFF


def main():
    out = ["// GENERATED by tools/make_sounds.py from firmware/services/audio/assets/ - do not edit.",
           "// 16 kHz mono, 8-bit mu-law. See summit/audio.h (ulaw_decode, sound_clip).",
           '#include "summit/audio.h"', "", "namespace summit {", "namespace {", ""]
    for name, file, start, end in SOUNDS:
        a = pcm(ASSETS / file, start, end)
        data = bytes(ulaw(v) for v in a)
        out.append(f"// {file}: {len(data)} samples, {len(data) / RATE:.2f} s")
        out.append(f"const uint8_t k_{name}[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out += ["};", ""]
    out += ["}  // namespace", "", "const SoundClip *sound_clip(Sound s)", "{", "    switch (s) {"]
    for name, *_ in SOUNDS:
        cls = {"warning": "Warning", "usb": "UsbPlug", "alarm": "Alarm"}[name]
        out += [f"    case Sound::{cls}: {{", f"        static const SoundClip c = {{k_{name}, sizeof k_{name}}};", "        return &c;", "    }"]
    out += ["    default: return nullptr;", "    }", "}", "", "}  // namespace summit", ""]
    OUT.write_text("\n".join(out))
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    sys.exit(main())
